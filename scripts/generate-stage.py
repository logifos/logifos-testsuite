#!/usr/bin/env python3
"""Generates the render stage's YAML case definitions.

Reads logifos-rs's per-font desired-render emission (`--desired <dir>` plus
its manifest) and the fetched corpus inputs, then writes
stages/mathml/generations/<generation>/payloads/<corpus>__<group>.yaml with
every covered row's input and per-font outcomes inline (each outcome carries
that font's desired SVG and laid-out metrics), plus the generation's
provenance.yaml.

Usage:
  generate-stage.py --rs-dir ../logifos-rs --emitted /tmp/desired \
      --manifest /tmp/desired/manifest.json
"""

import argparse
import hashlib
import json
import pathlib
import sys

import yaml

GENERATION = "000001"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rs-dir", required=True, type=pathlib.Path)
    parser.add_argument("--emitted", required=True, type=pathlib.Path,
                        help="the --desired emission directory (per-font tree)")
    parser.add_argument("--manifest", required=True, type=pathlib.Path,
                        help="the emission's manifest.json (format_version 2)")
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text())
    assert manifest["format_version"] == 2, "expect the per-font emission manifest"
    fonts = manifest["fonts"]
    metrics = manifest["metrics"]
    reference = args.rs_dir / "corpus" / "reference"

    # The emission nests out/<font>/<corpus>/<case>.svg; every font's tree
    # lists the same corpora.
    corpora = sorted({
        path.name
        for font_dir in args.emitted.iterdir()
        if font_dir.is_dir()
        for path in font_dir.iterdir()
        if path.is_dir()
    })

    payloads_dir = pathlib.Path("stages") / "mathml" / "generations" / GENERATION / "payloads"
    payloads_dir.mkdir(parents=True, exist_ok=True)

    total = 0
    sha_by_file = {}
    payload_cache = {}
    for corpus in corpora:
        rows_by_group = {}
        corpus_dir = reference / corpus
        for font in fonts:
            font_id = font["id"]
            for svg_path in sorted((args.emitted / font_id / corpus).glob("*.svg")):
                # The emission flattens case ids: __ stands for /.
                case_id = svg_path.stem.replace("__", "/")
                input_bytes = case_input(corpus_dir, corpus, case_id, payload_cache)
                if input_bytes is None:
                    sys.exit(f"no input source for {corpus}/{case_id}")
                key = f"{font_id}/{corpus}/{svg_path.name}"
                (width, height, depth) = metrics[key]
                group = payload_stem(corpus, case_id)
                rows_by_group.setdefault(group, {}).setdefault(case_id, []).append({
                    "font": font_id,
                    "sha256": font["sha256"],
                    "svg": svg_path.read_text(),
                    "metrics": [width, height, depth],
                    "input": input_bytes,
                })
        for group, rows in sorted(rows_by_group.items()):
            document = {
                "schema": "logifos-testsuite/render/2",
                "group": f"{corpus}/{group}",
                "description": f"Desired renders for {corpus} {group} rows.",
                "input_format": "mathml",
                "engine_version": manifest["engine_version"],
                "fonts": [font["id"] for font in fonts],
                "cases": [
                    {
                        "id": case_id,
                        "input": rows[case_id][0]["input"],
                        "outcomes": sorted(outcomes, key=lambda o: o["font"]),
                    }
                    for case_id, outcomes in sorted(rows.items())
                ],
            }
            body = yaml.safe_dump(
                document, allow_unicode=True, width=10_000, sort_keys=False
            )
            name = f"{corpus}__{group}.yaml"
            text = "# Generated by scripts/generate-stage.py. Do not edit.\n" + body
            (payloads_dir / name).write_text(text)
            digest = hashlib.sha256(text.encode()).hexdigest()
            sha_by_file[f"payloads/{name}"] = digest
            total += len(rows)

    provenance = {
        "schema": "logifos-testsuite/provenance/1",
        "language": "render",
        "generation": int(GENERATION),
        "engine": {
            "kind": "logifos-rs",
            "version": manifest["engine_version"],
            "generator": "logifos-corpus --desired; scripts/generate-stage.py",
        },
        "fonts": grading_fonts(args.rs_dir, manifest),
        "corpus_revisions": corpus_revisions(reference),
        "sha256": sha_by_file,
        "rows": total,
    }
    provenance_path = (
        pathlib.Path("stages") / "mathml" / "generations" / GENERATION / "provenance.yaml"
    )
    provenance_path.write_text(
        yaml.safe_dump(provenance, allow_unicode=True, sort_keys=False)
    )
    print(f"rows: {total}, payloads: {len(sha_by_file)}")
    return 0


def grading_fonts(rs_dir: pathlib.Path, manifest: dict) -> list:
    """The pinned provenance of each grading font, from fonts.json."""
    listing = json.loads((rs_dir / "corpus" / "fonts.json").read_text())
    pinned = {font["id"]: font for font in listing["fonts"]}
    fonts = []
    for font in manifest["fonts"]:
        entry = pinned[font["id"]]
        source = (
            {"kind": "git", "repository": entry["repository"], "revision": entry["revision"]}
            if "repository" in entry
            else {"kind": "fontist", "formula": entry["fontist_formula"]}
        )
        fonts.append({
            "id": font["id"],
            "sha256": font["sha256"],
            "face_index": entry["face_index"],
            "source": source,
        })
    return fonts


def payload_stem(corpus: str, case_id: str) -> str:
    """The group file name for a case id (the corpus's own grouping)."""
    if corpus == "plurimath-testsuite":
        # 000001/fractions/mathml-fractions-001 -> fractions
        return case_id.split("/")[1]
    if corpus == "lasem":
        # data/mathml/bugs/666974-... -> bugs
        return case_id.split("/")[2] if case_id.count("/") >= 2 else case_id
    return case_id.split("/")[0]


def corpus_revisions(reference: pathlib.Path) -> dict:
    sources = json.loads((reference / "sources.json").read_text())
    revisions = {}
    for source in sources["sources"]:
        revisions[source["id"]] = source["revision"]
    return revisions


def case_input(corpus_dir: pathlib.Path, corpus: str, case_id: str, payload_cache: dict):
    """The row's MathML input bytes, from the corpus's own layout."""
    if corpus == "plurimath-testsuite":
        # <generation>/<payload>/<case-id>
        generation, payload, case = case_id.split("/", 2)
        path = corpus_dir / "generations" / generation / "payloads" / f"{payload}.yaml"
        return payload_input(path, case, payload_cache)
    if corpus == "lasem":
        path = corpus_dir / case_id
        return path.read_text() if path.is_file() else None
    # The html-based corpora embed their rows in documents; their inputs are
    # the document spans, which the adapter re-derives from the source.
    path = corpus_dir / case_id.rsplit("#", 1)[0]
    return path.read_text() if path.is_file() else None


def payload_input(payload_path: pathlib.Path, case_id: str, cache: dict):
    """One row's input from a plurimath-testsuite payload file."""
    if payload_path not in cache:
        cache[payload_path] = yaml.safe_load(payload_path.read_text())
    for row in cache[payload_path].get("cases", []):
        if row["id"] == case_id:
            value = row["input"]
            if isinstance(value, str):
                return value
            return value["str"]
    return None


if __name__ == "__main__":
    sys.exit(main())
